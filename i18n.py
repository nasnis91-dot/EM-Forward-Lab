"""Very small translation layer.  English text is the key; Indonesian is looked up in ID.

    from i18n import tr
    tr("Run inversion")        -> "Run inversion" (EN) / "Jalankan inversi" (ID)
    tr("RMS = {v:.2f}", v=1)   -> formatted after translation
"""
from __future__ import annotations

LANG = "en"


def set_lang(lang: str):
    global LANG
    LANG = "id" if lang.lower().startswith("id") else "en"


def get_lang() -> str:
    return LANG


def tr(text: str, **kw) -> str:
    s = ID.get(text, text) if LANG == "id" else text
    return s.format(**kw) if kw else s


def pick(en: str, id_: str) -> str:
    """Inline bilingual text (for long paragraphs that are not shared)."""
    return id_ if LANG == "id" else en


